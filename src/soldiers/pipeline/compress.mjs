import { NodeIO, PropertyType } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, resample, meshopt, quantize } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { ktx2 } from 'ktx2-encoder/gltf-transform';
import sharp from 'sharp';
import { fixLegWeights } from './fixw.mjs';
const [,, src, dst] = process.argv;
await MeshoptEncoder.ready; await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });
const doc = await io.read(src);
const imageDecoder = async (buf) => { const { data, info } = await sharp(buf).ensureAlpha().raw().toBuffer({ resolveWithObject: true }); return { data: new Uint8Array(data), width: info.width, height: info.height }; };
fixLegWeights(doc);
await doc.transform(dedup({ propertyTypes: [PropertyType.ACCESSOR, PropertyType.MESH, PropertyType.TEXTURE] }), prune(), resample());
await doc.transform(ktx2({ isUASTC: false, qualityLevel: 230, generateMipmap: true, slots: /baseColor|occlusion|metallicRoughness/, imageDecoder }));
await doc.transform(ktx2({ isUASTC: true, generateMipmap: true, needSupercompression: true, uastcLDRQualityLevel: 2, slots: /normal/, imageDecoder }));
await doc.transform(meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
await io.write(dst, doc);
for (const t of doc.getRoot().listTextures()) console.log('tex', t.getName(), t.getMimeType(), t.getImage().byteLength);
